#!/usr/bin/env python3
"""Generate native/catalog_data.h/.cpp from the BPP ten-win build catalog.

Source: https://bpp-metrics.bazaarplusplus.com/analyzer-v5/builds/latest.json
The catalog is a compact index-encoded structure documented in
bazaarplusplus-mod/src/BazaarPlusPlus/Game/LiveBuildPanel/Recommendations/TenWinBuildCorpus.cs
"""
import json
import sys
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'evidence/bpp-builds.latest.json'
OUT = ROOT / 'mobilebpp/native'

data = json.loads(SRC.read_text(encoding="utf-8"))
cards = data["cards"]
heroes = data.get("heroes", {})
window = data.get("window", {})

lines_h = []
lines_h.append("// generated by tools/gen_catalog.py - do not edit")
lines_h.append("#pragma once")
lines_h.append("namespace catalog_data {")
lines_h.append("struct Row { int card_ref, slot, tier, enchant, size; };")
lines_h.append("struct Build { const int* refs; int refCount; const Row* rows; int rowCount;")
lines_h.append("                 int ten_win_runs, rate_bps, score; };")
lines_h.append("struct Hero { const char* hero; const Build* builds; int buildCount; };")
lines_h.append("extern const char* const kCardGuids[];")
lines_h.append("extern const int kCardGuidCount;")
lines_h.append("extern const Hero kHeroes[];")
lines_h.append("extern const int kHeroCount;")
lines_h.append("extern const char* const kTitle;")
lines_h.append("}  // namespace catalog_data")

lines_c = []
lines_c.append("// generated by tools/gen_catalog.py - do not edit")
lines_c.append('#include "catalog_data.h"')
lines_c.append("namespace catalog_data {")
lines_c.append("const char* const kCardGuids[] = {")
for g in cards:
    lines_c.append(f'    "{g}",')
if not cards:
    lines_c.append('    "",')
lines_c.append("};")
lines_c.append(f"const int kCardGuidCount = {max(len(cards),1)};")
lines_c.append("")

hero_names = sorted(heroes.keys())
for hi, hero in enumerate(hero_names):
    builds = heroes[hero].get("builds", [])
    for bi, build in enumerate(builds):
        refs, rows, stats = build[0], build[1], build[2]
        lines_c.append(f"static const int kRefs_{hi}_{bi}[] = {{{', '.join(str(x) for x in refs)}}};")
        row_txt = ", ".join(
            "{%d,%d,%d,%d,%d}" % (r[0], r[1], r[2], r[3], r[4]) for r in rows
        )
        lines_c.append(f"static const Row kRows_{hi}_{bi}[] = {{{row_txt}}};")
        lines_c.append(
            f"static const Build kBuild_{hi}_{bi} = {{kRefs_{hi}_{bi}, {len(refs)}, "
            f"kRows_{hi}_{bi}, {len(rows)}, {stats[1]}, {stats[2]}, {stats[4]}}};"
        )

lines_c.append("")
for hi, hero in enumerate(hero_names):
    builds = heroes[hero].get("builds", [])
    if builds:
        arr = ", ".join(f"kBuild_{hi}_{bi}" for bi in range(len(builds)))
        lines_c.append(f"static const Build kBuilds_{hi}[] = {{{arr}}};")
    else:
        lines_c.append("static const Build kBuilds_%d[] = {{nullptr,0,nullptr,0,0,0,0}};" % hi)

lines_c.append("")
lines_c.append("const Hero kHeroes[] = {")
for hi, hero in enumerate(hero_names):
    n = len(heroes[hero].get("builds", []))
    lines_c.append(f'    {{"{hero}", kBuilds_{hi}, {n}}},')
lines_c.append("};")
lines_c.append(f"const int kHeroCount = {len(hero_names)};")
title = "BPP ten-win builds · %s..%s · %s" % (
    window.get("start", "?"),
    window.get("end", "?"),
    data.get("generated_at", "?")[:10],
)
lines_c.append(f'const char* const kTitle = "{title}";')
lines_c.append("}  // namespace catalog_data")

(OUT / "catalog_data.h").write_text("\n".join(lines_h) + "\n", encoding="utf-8")
(OUT / "catalog_data.cpp").write_text("\n".join(lines_c) + "\n", encoding="utf-8")

total = sum(len(heroes[h].get("builds", [])) for h in hero_names)
print(f"wrote {OUT/'catalog_data.cpp'}  cards={len(cards)} heroes={len(hero_names)} builds={total}")
