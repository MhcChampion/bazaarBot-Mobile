"""Generate native headers from the editable web panel and Java bridge DEX."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def embed_web():
    parts = []
    for name, symbol in [('panel.html', 'kPanelHtml'), ('panel.css', 'kPanelCss'), ('panel.js', 'kPanelJs')]:
        text = (ROOT / 'web' / name).read_text(encoding='utf-8')
        if ')BPPASSET"' in text:
            raise ValueError('raw-string delimiter found in asset')
        parts.append(f'static const char {symbol}[] = R"BPPASSET({text})BPPASSET";\n')
    for file, symbol in [(ROOT / 'web/cards.json', 'kCardsJson'), (ROOT / 'web/frame-report.json', 'kFramesJson'), (ROOT / 'web/theme-report.json', 'kThemeJson')]:
        text = json.dumps(json.loads(file.read_text(encoding='utf-8')), ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c')
        parts.append(f'static const char {symbol}[] = R"BPPASSET({text})BPPASSET";\n')
    (ROOT / 'native/bpp_web_assets.h').write_text('// Generated by tools/embed_assets.py.\n#pragma once\n' + ''.join(parts), encoding='utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--dex', type=Path)
    args = parser.parse_args()
    if args.dex:
        data = args.dex.read_bytes()
        rows = [', '.join(f'0x{b:02x}' for b in data[i:i+16]) for i in range(0, len(data), 16)]
        content = '// Generated from java/bpp/Ui.java by tools/build_dex.ps1.\n#pragma once\n'
        content += 'static const unsigned char kBppDex[] = {\n' + '\n'.join('    ' + row + ',' for row in rows) + '\n};\n'
        content += f'static const int kBppDexLen = {len(data)};\n'
        (ROOT / 'native/bpp_dex.h').write_text(content, encoding='utf-8')
        print(f'embedded DEX: {len(data)} bytes')
    else:
        embed_web()
